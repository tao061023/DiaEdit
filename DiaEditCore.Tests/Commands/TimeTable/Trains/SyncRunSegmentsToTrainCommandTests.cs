    // -----------------------------
    // Undo
    // -----------------------------

    [Fact]
    public void UndoでRunSegmentsとStopTimesが元の状態に戻る()
    {
        var mainRoute = MakeMainRoute(1, StA, StB, StC);
        var seg1 = MakeSegment(1, StA, StB);
        var seg2 = MakeSegment(2, StB, StC);
        var sc = MakeConnection(1, 1, StationConnectionDirection.Down, seg1.Id, seg2.Id);
        var serviceRoute = MakeServiceRoute(1, MakeSrSegment(1, 0, 2, sc.Id));

        var train = MakeValidTrain(1);
        train.RunSegments.Add(new TrainRunSegment { FromStationId = StA, ToStationId = StB, StationConnectionId = sc.Id });
        var originalStopTime = new StopTime();
        train.StopTimesInternal[new StopKey(StB, 0)] = originalStopTime; // Syncで孤立・破棄される想定のキー

        var session = MakeSession();
        var command = SyncRunSegmentsToTrainCommand.Create(
            train, serviceRoute, [mainRoute], [sc], [seg1, seg2], session);
        command.Execute();

        Assert.Equal(2, train.RunSegments.Count); // A-B, B-C に増える

        command.Undo();

        Assert.Single(train.RunSegments);
        Assert.Same(originalStopTime, train.StopTimesInternal[new StopKey(StB, 0)]);
    }

