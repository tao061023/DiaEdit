        var serviceRoute = MakeServiceRoute(1, MakeSrSegment(1, 0, 1, defaultSc.Id));

        var train = MakeValidTrain(1);
        train.RunSegments.Add(new TrainRunSegment
        {
            FromStationId = StA,
            ToStationId = StB,
            StationConnectionId = staleSc.Id,
            IsOverriddenFromTemplate = false,
