    [Fact]
    public void 境界駅が一致していれば合格()
    {
        var routeA = new MainRoute { Id = new MainRouteId(1), Name = new DisplayName { Name = "A線" }, StationOrder = [new StationId(1), new StationId(2)] };
        var routeB = new MainRoute { Id = new MainRouteId(2), Name = new DisplayName { Name = "B線" }, StationOrder = [new StationId(2), new StationId(3)] };

        var scA = new StationConnection { Id = new StationConnectionId(1), Name = "A下り", MainRouteId = routeA.Id, Direction = StationConnectionDirection.Down, Segments = [] };
        var scAUp = new StationConnection { Id = new StationConnectionId(2), Name = "A上り", MainRouteId = routeA.Id, Direction = StationConnectionDirection.Up, Segments = [] };
        var scB = new StationConnection { Id = new StationConnectionId(3), Name = "B下り", MainRouteId = routeB.Id, Direction = StationConnectionDirection.Down, Segments = [] };
        var scBUp = new StationConnection { Id = new StationConnectionId(4), Name = "B上り", MainRouteId = routeB.Id, Direction = StationConnectionDirection.Up, Segments = [] };

        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1),
            Name = new DisplayName { Name = "テスト系統" },
            IsAutoGenerated = false,
            Segments =
            [
                new ServiceRouteSegment { MainRouteId = routeA.Id, FromStationIndex = 0, ToStationIndex = 1 },
                new ServiceRouteSegment { MainRouteId = routeB.Id, FromStationIndex = 0, ToStationIndex = 1 },
