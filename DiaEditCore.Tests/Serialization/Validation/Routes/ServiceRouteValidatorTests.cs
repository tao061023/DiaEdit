    private static Rail TrackRail(int id, RailEndpointRef a, RailEndpointRef b) => new()
    {
        Id = new RailId(id), LengthM = 100, SpeedLimitKph = 60, Role = RailRole.Track,
        EndpointA = a, EndpointB = b,
