                new() { MainRouteId = mainRouteId, FromStationIndex = 0, ToStationIndex = 2 },
            },
        };

        return (sr, route, sc, new List<StationConnectionSegment> { seg0, seg1 },
            new List<StationPath> { arrivalPath, departurePath }, new List<Rail> { trackB });
    }

