public class ServiceRouteValidatorPairedMixingTests
{
    // §8.2項目5（旧6）：IsUnidirectional=trueのSegment群内でPaired設定済み／未設定の混在を禁止する

    private static ServiceRouteSegment UniSeg(int mainRouteId, bool paired) => new()
    {
        MainRouteId = new MainRouteId(mainRouteId),
        FromStationIndex = 0,
        ToStationIndex = 1,
        IsUnidirectional = true,
        PairedMainRouteId = paired ? new MainRouteId(mainRouteId + 100) : null,
        PairedFromStationIndex = paired ? 0 : null,
        PairedToStationIndex = paired ? 1 : null,
    };

    [Fact]
    public void 全SegmentがUnidirectionalかつ全てPaired設定済みなら混在エラーは出ない()
    {
        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1), Name = new DisplayName{ Name = "sr"}, IsAutoGenerated = false,
            Segments = [UniSeg(1, paired: true), UniSeg(2, paired: true)],
        };
        var context = new ValidationContext();

        var issues = new ServiceRouteValidator().Validate(sr, context);

        Assert.DoesNotContain(issues, i => i.Message.Contains("Paired設定が一部のみ存在する"));
    }

    [Fact]
    public void 全SegmentがUnidirectionalかつ全てPaired未設定なら混在エラーは出ない()
    {
        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1), Name = new DisplayName{ Name = "sr"}, IsAutoGenerated = false,
            Segments = [UniSeg(1, paired: false), UniSeg(2, paired: false)],
        };
        var context = new ValidationContext();

        var issues = new ServiceRouteValidator().Validate(sr, context);

        Assert.DoesNotContain(issues, i => i.Message.Contains("Paired設定が一部のみ存在する"));
    }

    [Fact]
    public void UnidirectionalSegmentでPaired設定が一部のみだと混在エラーになる()
    {
        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1), Name = new DisplayName{ Name = "sr"}, IsAutoGenerated = false,
            Segments = [UniSeg(1, paired: true), UniSeg(2, paired: false)],
        };
        var context = new ValidationContext();

        var issues = new ServiceRouteValidator().Validate(sr, context);

        Assert.Contains(issues, i => i.Message.Contains("Paired設定が一部のみ存在する") && i.Message.Contains("1/2件"));
    }

    [Fact]
    public void NonUnidirectionalSegmentはPaired混在判定の母数に含まれない()
    {
        // seg1: Unidirectional=true・Paired未設定, seg2: Unidirectional=false（母数から除外されるべき）
        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1), Name = new DisplayName{ Name = "sr"}, IsAutoGenerated = false,
            Segments =
            [
                UniSeg(1, paired: false),
                new ServiceRouteSegment { MainRouteId = new MainRouteId(2), FromStationIndex = 0, ToStationIndex = 1, IsUnidirectional = false },
            ],
        };
        var context = new ValidationContext();

        var issues = new ServiceRouteValidator().Validate(sr, context);

        // UnidirectionalなSegmentが1件のみ（母数1）なので、mixing自体が原理的に発生しない
        Assert.DoesNotContain(issues, i => i.Message.Contains("Paired設定が一部のみ存在する"));
    }

