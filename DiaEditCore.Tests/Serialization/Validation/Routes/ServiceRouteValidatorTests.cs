    private static StationPath Path(int id, StationPathDirection dir, params StationPathWaypoint[] wps) => new()
    {
        Id = new StationPathId(id), FloorUnitId = new FloorUnitId(1), Name = $"path{id}",
        Direction = dir, Waypoints = wps.ToList(),
    };

    private static MainRoute MakeRoute(MainRouteId id, bool isLoop, params StationId[] stations) => new()
    {
        Id = id, Name = new DisplayName { Name = "route" }, StationOrder = stations.ToList(), IsLoop = isLoop,
