    [Fact]
    public void ルール5_2MainRouteでA発A着のループ構成なら先頭末尾境界も検証対象になる()
    {
        var stA = new StationId(1);
        var stB = new StationId(2);
        var mainRouteAId = new MainRouteId(1);
        var mainRouteBId = new MainRouteId(2);

        // MainRouteA: A(0)→B(1)。B駅で出発線・到着線が同一Trackに接続する構成にする。
        var epA1 = new EntryPointId(1);       // A駅側出発（MainRouteA始点）
        var epB1Arr = new EntryPointId(2);    // B駅側到着（MainRouteA終点）
        var seg1 = new StationConnectionSegment
        {
            Id = new StationConnectionSegmentId(1), FromStationId = stA, ToStationId = stB,
            FromEntryPointId = epA1, ToEntryPointId = epB1Arr, MainRouteId = mainRouteAId,
        };
        var scA = new StationConnection
        {
            Id = new StationConnectionId(1), Name = "scA", MainRouteId = mainRouteAId,
            Direction = StationConnectionDirection.Down, Segments = new List<StationConnectionSegmentId> { seg1.Id },
        };
        var routeA = MakeRoute(mainRouteAId, isLoop: false, stA, stB);

        // MainRouteB: B(0)→A(1)。B駅側出発EPをMainRouteAの到着EPと同一Trackに接続、
        // A駅側到着EPをMainRouteAの出発EPと同一Trackに接続することで、両方の境界を連結させる。
        var epB2Dep = new EntryPointId(3);    // B駅側出発（MainRouteB始点）
        var epA2Arr = new EntryPointId(4);    // A駅側到着（MainRouteB終点、ループを閉じる）
        var seg2 = new StationConnectionSegment
        {
            Id = new StationConnectionSegmentId(2), FromStationId = stB, ToStationId = stA,
            FromEntryPointId = epB2Dep, ToEntryPointId = epA2Arr, MainRouteId = mainRouteBId,
        };
        var scB = new StationConnection
        {
            Id = new StationConnectionId(2), Name = "scB", MainRouteId = mainRouteBId,
            Direction = StationConnectionDirection.Down, Segments = new List<StationConnectionSegmentId> { seg2.Id },
        };
        var routeB = MakeRoute(mainRouteBId, isLoop: false, stB, stA);

        // B駅境界：MainRouteAの到着EP(epB1Arr)とMainRouteBの出発EP(epB2Dep)が同一Trackに接続
        var bpB = new BoundaryPointId(10);
        var trackB = TrackRail(1, new EntryPointEndpointRef(epB1Arr), new BoundaryPointEndpointRef(bpB));
        var arrivalAtB = Path(1, StationPathDirection.Arrival, new EntryPointWaypoint(epB1Arr), new BoundaryPointWaypoint(bpB));
        var departureAtB = Path(2, StationPathDirection.Departure, new BoundaryPointWaypoint(bpB), new EntryPointWaypoint(epB2Dep));

        // A駅ループ境界：MainRouteBの到着EP(epA2Arr)とMainRouteAの出発EP(epA1)が同一Trackに接続（成立ケース）
        var bpA = new BoundaryPointId(11);
        var trackA = TrackRail(2, new EntryPointEndpointRef(epA2Arr), new BoundaryPointEndpointRef(bpA));
        var arrivalAtA = Path(3, StationPathDirection.Arrival, new EntryPointWaypoint(epA2Arr), new BoundaryPointWaypoint(bpA));
        var departureAtA = Path(4, StationPathDirection.Departure, new BoundaryPointWaypoint(bpA), new EntryPointWaypoint(epA1));

        var sr = new ServiceRoute
        {
            Id = new ServiceRouteId(1), Name = new DisplayName{ Name = "loop-sr"}, IsAutoGenerated = false,
            Segments = new List<ServiceRouteSegment>
            {
                new() { MainRouteId = mainRouteAId, FromStationIndex = 0, ToStationIndex = 1 }, // A→B
                new() { MainRouteId = mainRouteBId, FromStationIndex = 0, ToStationIndex = 1 }, // B→A
            },
        };

        var context = new ValidationContext
        {
            MainRoutes = new[] { routeA, routeB },
            StationConnections = new[] { scA, scB },
            StationConnectionSegments = new List<StationConnectionSegment> { seg1, seg2 },
            StationPaths = new List<StationPath> { arrivalAtB, departureAtB, arrivalAtA, departureAtA },
            Rails = new List<Rail> { trackB, trackA },
        };

        var issues = new ServiceRouteValidator().Validate(sr, context);

        // B駅境界(Segment内部境界)・Aループ境界(先頭末尾境界)とも整合するため、境界駅整合性エラーは出ない
        Assert.DoesNotContain(issues, i => i.Message.Contains("境界駅の整合性条件"));
    }

