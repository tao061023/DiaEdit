    }
    [Fact]
    public void RunSegmentsがServiceRouteの現在のStationOrderと一致すれば合格()
    {
        var stA = new StationId(1);
        var stB = new StationId(2);
        var stC = new StationId(3);
        var mainRoute = MakeMainRoute(1, stA, stB, stC);
        var serviceRoute = MakeServiceRouteWithSegment(1, mainRouteId: 1, fromIndex: 0, toIndex: 2);

        var train = MakeValidTrain(1);
        train.RunSegments.Add(new TrainRunSegment { FromStationId = stA, ToStationId = stB, StationConnectionId = new StationConnectionId(1) });
        train.RunSegments.Add(new TrainRunSegment { FromStationId = stB, ToStationId = stC, StationConnectionId = new StationConnectionId(1) });

        var context = MakeBaseContext([train], serviceRoutes: [serviceRoute], mainRoutes: [mainRoute]);

        var issues = new TrainValidator().Validate(train, context);

        Assert.DoesNotContain(issues, i => i.Message.Contains("StationOrder"));
    }

    [Fact]
    public void StationOrder変更後にRunSegmentsが未同期なら不合格()
    {
        var stA = new StationId(1);
        var stB = new StationId(2);
        var stC = new StationId(3);
        var stD = new StationId(4); // StationOrder変更で新たに挿入された駅
        var mainRoute = MakeMainRoute(1, stA, stB, stD, stC); // B-C間にDが挿入された、という想定
        var serviceRoute = MakeServiceRouteWithSegment(1, mainRouteId: 1, fromIndex: 0, toIndex: 3);

        var train = MakeValidTrain(1);
        // Train側はまだ古い駅順（A→B→C）のまま同期していない
        train.RunSegments.Add(new TrainRunSegment { FromStationId = stA, ToStationId = stB, StationConnectionId = new StationConnectionId(1) });
        train.RunSegments.Add(new TrainRunSegment { FromStationId = stB, ToStationId = stC, StationConnectionId = new StationConnectionId(1) });

        var context = MakeBaseContext([train], serviceRoutes: [serviceRoute], mainRoutes: [mainRoute]);

        var issues = new TrainValidator().Validate(train, context);

        Assert.Contains(issues, i => i.Message.Contains("StationOrder") && i.Message.Contains("同期"));
    }

    [Fact]
    public void ServiceRouteにSegmentsが未設定なら陳腐化チェックはスキップされ合格()
    {
        // MakeServiceRoute(1)のデフォルトはSegments=[]。ServiceRoute自体が未構築なだけであり、
        // 「StationOrder変更によりTrainが陳腐化した」ケースとは区別する（ServiceRouteValidator側の責務）。
        var train = MakeValidTrain(1);
        train.RunSegments.Add(new TrainRunSegment { FromStationId = new StationId(1), ToStationId = new StationId(2), StationConnectionId = new StationConnectionId(1) });

        var context = MakeBaseContext([train]); // serviceRoutes未指定＝デフォルト(Segments=[])

        var issues = new TrainValidator().Validate(train, context);

        Assert.DoesNotContain(issues, i => i.Message.Contains("StationOrder"));
    }
